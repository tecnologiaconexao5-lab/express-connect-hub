import pg from "pg";
import fs from "node:fs";
import crypto from "node:crypto";
const env = fs.readFileSync(".env", "utf8");
const cs = env.match(/^DATABASE_URL=(.+)$/m)[1].trim();
const p = new pg.Pool({ connectionString: cs, ssl: { rejectUnauthorized: false } });
const q = async (s, pr = []) => (await p.query(s, pr)).rows;
const out = {};
out.col_numero_cliente = await q(`select column_name from information_schema.columns where table_schema='public' and table_name='faturas' and column_name='numero_cliente'`);
out.tbl_contador = await q(`select to_regclass('public.fatura_contadores_cliente')::text t`);
out.idx = await q(`select indexname from pg_indexes where schemaname='public' and indexname in ('uq_faturas_numero_cliente','uq_receber_fatura_id') order by 1`);
out.trg = await q(`select tgname from pg_trigger where tgrelid='public.faturas'::regclass and not tgisinternal`);
const fn = await q(`select pg_get_functiondef(p.oid) def from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname='f_emitir_fatura'`);
out.fn_emitir_sha = fn[0] ? crypto.createHash("sha256").update(fn[0].def).digest("hex").slice(0,16) : null;
out.fn_emitir_has_numero_cliente = fn[0] ? fn[0].def.includes("numero_cliente") : null;
out.grants = await q(`select grantee from information_schema.routine_privileges where routine_schema='public' and routine_name='f_emitir_fatura' order by 1`);
out.faturas_emitidas_sem_ar = (await q(`select count(*)::int n from faturas where status='emitida' and conta_receber_id is null`))[0].n;
out.faturas_total = (await q(`select count(*)::int n from faturas`))[0].n;
console.log(JSON.stringify(out, null, 2));
await p.end();
